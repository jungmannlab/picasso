def test_export_filters_picks_by_probability(predicted, data_dir):
    locs = predicted.locs
    locs.loc[locs["group"] == 1, "score"] = 0.5  # a double dot
    predicted.filter_accuracy_btn.setChecked(True)
    predicted.export_accuracy.setValue(0.9)
    locs.loc[locs["group"] != 1, "score"] = 0.95

    predicted.export_btn.click()

    doubles, info = io.load_locs(str(data_dir / "locs_double_dot.hdf5"))
    assert len(doubles) == (TRUTH.count(DOUBLE) - 1) * N_LOCS
    assert info[-1]["Probability"] == pytest.approx(0.9)
    singles, _ = io.load_locs(str(data_dir / "locs_single.hdf5"))
    assert len(singles) == TRUTH.count(SINGLE) * N_LOCS

    # a later export without the filter does not claim it
    predicted.filter_accuracy_btn.setChecked(False)
    predicted.export_btn.click()
    doubles, info = io.load_locs(str(data_dir / "locs_double_dot.hdf5"))
    assert len(doubles) == TRUTH.count(DOUBLE) * N_LOCS
    assert "Probability" not in info[-1]


