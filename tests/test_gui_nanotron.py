def test_a_failing_training_is_reported(
    train, qt_offscreen, train_files, monkeypatch
):
    """E.g., a network the solver rejects; training used to stay
    "running" for good."""
    _fill(train, train_files)
    _prepare(train, qt_offscreen)

    def fail(self, X, y):
        raise ValueError("solver failed")

    monkeypatch.setattr(gui_nanotron.MLPClassifier, "fit", fail)
    _train(train, qt_offscreen)

    assert not train.trainer_running
    assert "solver failed" in train.window.dialogs.texts()
    assert not train.save_model_btn.isVisibleTo(train)
    assert train.train_label.text() != "Model is training..."


