def test_dropping_a_file_on_the_view_opens_it(window, locs_path):
    class Event:
        def __init__(self, path):
            self.path = path

        def mimeData(self):
            mime = gui_nanotron.QtCore.QMimeData()
            mime.setUrls([gui_nanotron.QtCore.QUrl.fromLocalFile(self.path)])
            return mime

    window.view.dropEvent(Event(str(locs_path)[:-5] + ".csv"))
    assert not window.locs_loaded

    window.view.dropEvent(Event(locs_path))
    assert window.locs_loaded
    assert window.path == locs_path


