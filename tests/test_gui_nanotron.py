def _picks(kinds, groups=None, seed=0) -> pd.DataFrame:
    """Picked localizations, one pick per entry of ``kinds``: a single
    dot (``SINGLE``) or two dots 60 nm apart (``DOUBLE``), on a grid of
    350 nm."""
    rng = np.random.default_rng(seed)
    groups = range(len(kinds)) if groups is None else groups
    picks = []
    for i, (kind, group) in enumerate(zip(kinds, groups)):
        x0 = 300.0 + (i % 10) * 350.0
        y0 = 300.0 + (i // 10) * 350.0
        dx = np.zeros(N_LOCS)
        if kind == DOUBLE:
            half = N_LOCS // 2
            dx[:half] = -30.0
            dx[half:] = 30.0
        picks.append(
            pd.DataFrame(
                {
                    "x": x0 + dx + rng.normal(0, 3.0, N_LOCS),
                    "y": y0 + rng.normal(0, 3.0, N_LOCS),
                    "lpx": np.full(N_LOCS, 3.0),
                    "lpy": np.full(N_LOCS, 3.0),
                    "group": np.full(N_LOCS, group),
                }
            )
        )
    locs = pd.concat(picks, ignore_index=True)
    locs.insert(0, "frame", np.arange(len(locs)))
    return locs


def _info(n_frames: int, diameter: float | None = DIAMETER) -> list[dict]:
    info = [
        {
            "Width": 32,
            "Height": 32,
            "Frames": n_frames,
            "Pixelsize": PIXELSIZE,
        }
    ]
    if diameter is not None:
        info.append(
            {
                "Generated by": "Picasso Render : Pick",
                "Pick Diameter (nm)": diameter,
            }
        )
    return info


def _save_picks(path, kinds, groups=None, seed=0, diameter=DIAMETER):
    locs = _picks(kinds, groups=groups or None, seed=seed)
    if groups is False:
        locs = locs.drop(columns="group")
    io.save_locs(str(path), locs, _info(len(locs), diameter))
    return str(path)


def _model_info(**kwargs) -> dict:
    info = {
        "Classes": dict(CLASSES),
        "Pick Diameter (nm)": DIAMETER,
        "Display pixel size (nm)": DISP_PX_SIZE,
        io.FORMAT_VERSION_ATTR: io.FORMAT_VERSION,
    }
    info.update(kwargs)
    return info


def _save_model(path, mlp, info) -> str:
    joblib.dump(mlp, str(path))
    io.save_info(os.path.splitext(str(path))[0] + ".yaml", [info])
    return str(path)


