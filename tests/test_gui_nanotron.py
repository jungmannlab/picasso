def _outputs(data_dir) -> set[str]:
    return {
        name
        for name in os.listdir(data_dir)
        if name not in {"locs.hdf5", "locs.yaml", "model.sav", "model.yaml"}
    }


def test_export_writes_one_regrouped_file_per_class(predicted, data_dir):
    predicted.export_btn.click()

    assert _outputs(data_dir) - {
        "locs_single.yaml",
        "locs_double_dot.yaml",
    } == {"locs_single.hdf5", "locs_double_dot.hdf5"}
    for label, name in [(SINGLE, "single"), (DOUBLE, "double_dot")]:
        locs, info = io.load_locs(str(data_dir / f"locs_{name}.hdf5"))
        n_picks = TRUTH.count(label)
        assert (locs["prediction"] == label).all()
        assert len(locs) == n_picks * N_LOCS
        # regrouped to 0, 1, ...
        assert sorted(locs["group"].unique()) == list(range(n_picks))
        assert info[-1]["Model Path"] == str(data_dir / "model.sav")
        assert info[-1]["Regroup"] is True
        assert "Probability" not in info[-1]
        assert info[-2]["Pick Diameter (nm)"] == DIAMETER
    assert predicted.status_bar.currentMessage() == "2 files exported."


