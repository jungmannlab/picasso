def _wait(thread, qapp) -> None:
    """Let a worker thread finish and deliver its signals."""
    assert thread.wait(WAIT_MS), "the worker thread did not finish"
    qapp.processEvents()


def _stop_threads(*owners) -> None:
    """Never leave a QThread running at the end of a test: Qt aborts
    the process when one is destroyed while running."""
    for owner in owners:
        for name in ("thread", "generate_thread", "train_thread"):
            thread = owner.__dict__.get(name)
            if isinstance(thread, gui_nanotron.QtCore.QThread):
                thread.wait(WAIT_MS)


@pytest.fixture
def window(qt_offscreen, dialogs):
    window = gui_nanotron.Window()
    window.dialogs = dialogs
    yield window
    _stop_threads(window, window.train_dialog)
    qt_offscreen.processEvents()
    window.close()


def _open(window, path) -> None:
    window.dialogs.open_path = str(path)
    window.open()


def _load_model(window, path) -> None:
    window.dialogs.open_path = str(path)
    window.load_model()


def _predict(window, qapp) -> None:
    window.predict_btn.click()
    _wait(window.thread, qapp)


def _class_boxes(window) -> list:
    layout = window.classbox_grid
    return [
        layout.itemAt(i).widget()
        for i in range(layout.count())
        if layout.itemAt(i).widget() is not None
    ]


def _pick_classes(locs) -> list[int]:
    """The predicted class of each pick, checking that all localizations
    of a pick share it."""
    classes = []
    for _, pick in locs.groupby("group"):
        assert pick["prediction"].nunique() == 1
        assert pick["score"].nunique() == 1
        classes.append(int(pick["prediction"].iloc[0]))
    return classes


