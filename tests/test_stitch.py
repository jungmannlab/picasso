"""Test ``picasso.stitch``.

The tiles are cut out of one simulated sample of random binding sites,
each tile with its own localizations of the sites, so the true offsets
between the tiles are known.

:author: Rafal Kowalewski, 2026
:copyright: Copyright (c) 2026 Jungmann Lab, MPI of Biochemistry
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import pytest

from picasso import __main__ as cli
from picasso import io, stitch

PIXELSIZE = 130.0  # nm
FRAMES = 1000
PRECISION = 0.1  # camera pixels


def _sample(rng, width, height, density=0.05):
    """Random binding sites (x, y in camera pixels, z in nm)."""
    n = int(width * height * density)
    return np.column_stack(
        [
            rng.uniform(0, width, n),
            rng.uniform(0, height, n),
            rng.uniform(-300, 300, n),
        ]
    )


def _tile_locs(rng, sites, origin, size, z_shift, per_site=4, site_ids=None):
    """Localizations of the sites inside one tile, in its camera
    frame, with ``z_shift`` subtracted from z."""
    inside = (
        (sites[:, 0] >= origin[0])
        & (sites[:, 0] < origin[0] + size[0])
        & (sites[:, 1] >= origin[1])
        & (sites[:, 1] < origin[1] + size[1])
    )
    ids = np.flatnonzero(inside) if site_ids is None else site_ids[inside]
    local = sites[inside]
    n = len(local) * per_site
    rep = np.repeat(local, per_site, axis=0)
    x = rep[:, 0] - origin[0] + rng.normal(0, PRECISION, n)
    y = rep[:, 1] - origin[1] + rng.normal(0, PRECISION, n)
    keep = (x >= 0) & (x < size[0]) & (y >= 0) & (y < size[1])
    locs = pd.DataFrame(
        {
            "frame": rng.integers(0, FRAMES, n).astype(np.uint32),
            "x": x.astype(np.float32),
            "y": y.astype(np.float32),
            "z": (rep[:, 2] - z_shift + rng.normal(0, 5, n)).astype(
                np.float32
            ),
            "photons": np.full(n, 1000, dtype=np.float32),
            "lpx": np.full(n, PRECISION, dtype=np.float32),
            "lpy": np.full(n, PRECISION, dtype=np.float32),
            "site": np.repeat(ids, per_site),
        }
    )
    return locs[keep].sort_values("frame").reset_index(drop=True)


def _info(size, stage_um=None, received=None):
    """Metadata of a tile, optionally with a Micro-Manager stage
    position (micrometers) and acquisition time."""
    info = [
        {
            "Width": int(size[0]),
            "Height": int(size[1]),
            "Frames": FRAMES,
        },
        {"Generated by": "test", "Pixelsize": PIXELSIZE},
    ]
    if stage_um is not None:
        mm = {"XPositionUm": stage_um[0], "YPositionUm": stage_um[1]}
        if received is not None:
            mm["ReceivedTime"] = received
        info[0]["Micro-Manager Metadata"] = mm
    return info


def _grid(
    rng,
    n_cols=3,
    n_rows=2,
    size=(500, 400),
    overlap=60,
    jitter=20,
    orientation="-x, y",
    sizes=None,
):
    """Tiles of a simulated sample on a grid.

    The stage positions are those of the nominal grid, the true tile
    origins are off by up to ``jitter`` camera pixels.

    Returns
    -------
    locs, infos : lists
        One per tile.
    origins : np.ndarray
        True tile origins in camera pixels.
    z_shifts : np.ndarray
        z subtracted from each tile in nm.
    """
    n = n_cols * n_rows
    if sizes is None:
        sizes = np.tile(size, (n, 1))
    step = np.array(size) - overlap
    nominal = np.array(
        [
            [c * step[0], r * step[1]]
            for r in range(n_rows)
            for c in range(n_cols)
        ],
        dtype=float,
    )
    origins = nominal + rng.uniform(-jitter, jitter, (n, 2))
    origins -= origins.min(axis=0) - 50  # margin
    sites = _sample(
        rng,
        (origins[:, 0] + sizes[:, 0]).max() + 50,
        (origins[:, 1] + sizes[:, 1]).max() + 50,
    )
    z_shifts = rng.uniform(-150, 150, n)
    # stage = matrix^-1 @ image position (the matrices are orthogonal)
    matrix = np.array(stitch.ORIENTATIONS[orientation], dtype=float)
    stage = nominal @ matrix * PIXELSIZE / 1e3 + (1000.0, -500.0)
    locs, infos = [], []
    for t in range(n):
        locs.append(_tile_locs(rng, sites, origins[t], sizes[t], z_shifts[t]))
        received = f"2024-08-05 15:{10 + t:02d}:00.000 +0200"
        infos.append(_info(sizes[t], stage[t], received))
    return locs, infos, origins, z_shifts


def _relative(positions):
    return positions - positions[0]


class TestStitch:
    def test_recovers_positions_orientation_and_z(self):
        rng = np.random.default_rng(0)
        locs, infos, origins, z_shifts = _grid(rng)
        out, out_infos, report = stitch.stitch(locs, infos)
        assert report["orientation"] == "-x, y"
        np.testing.assert_allclose(
            _relative(report["positions"]), _relative(origins), atol=0.05
        )
        # z_shift was subtracted, so the offsets restore it (relative
        # to the first tile)
        np.testing.assert_allclose(
            report["z_offsets"], z_shifts - z_shifts[0], atol=2.0
        )
        assert report["unconnected"] == []
        assert len(out) == 1
        info = out_infos[0]
        entry = info[-1]
        assert entry["Generated by"].endswith("Stitch")
        assert entry["Stage orientation"] == "-x, y"
        # the stitched canvas holds every localization
        assert out[0]["x"].min() >= 0 and out[0]["y"].min() >= 0
        assert out[0]["x"].max() < info[0]["Width"]
        assert out[0]["y"].max() < info[0]["Height"]

    def test_explicit_orientation_and_positions(self):
        rng = np.random.default_rng(1)
        locs, infos, origins, _ = _grid(rng, n_cols=2, n_rows=2)
        _, _, report = stitch.stitch(locs, infos, orientation="-x, y")
        np.testing.assert_allclose(
            _relative(report["positions"]), _relative(origins), atol=0.05
        )
        # without stage positions, from rough positions (e.g., placed
        # by hand); the error is within the search radius
        for info in infos:
            del info[0]["Micro-Manager Metadata"]
        rough = origins + rng.uniform(-20, 20, origins.shape)
        _, _, report = stitch.stitch(locs, infos, positions=rough)
        assert report["orientation"] is None
        np.testing.assert_allclose(
            _relative(report["positions"]), _relative(origins), atol=0.05
        )

    def test_tiles_of_different_sizes(self):
        rng = np.random.default_rng(2)
        sizes = np.array([[500, 400], [480, 400], [500, 370], [450, 330]])
        locs, infos, origins, _ = _grid(rng, n_cols=2, n_rows=2, sizes=sizes)
        out, out_infos, report = stitch.stitch(locs, infos)
        np.testing.assert_allclose(
            _relative(report["positions"]), _relative(origins), atol=0.05
        )
        assert out[0]["x"].max() < out_infos[0][0]["Width"]
        assert out[0]["y"].max() < out_infos[0][0]["Height"]

    def test_seams_cut_each_site_from_one_tile(self):
        rng = np.random.default_rng(3)
        locs, infos, _, _ = _grid(rng, n_cols=2, n_rows=2)
        for t, locs_ in enumerate(locs):
            locs_["tile"] = t
        n_total = sum(len(locs_) for locs_ in locs)
        out, _, _ = stitch.stitch(locs, infos, cut_seams=False)
        assert len(out[0]) == n_total
        tiles_per_site = out[0].groupby("site")["tile"].nunique()
        assert (tiles_per_site > 1).mean() > 0.05  # overlaps doubled

        out, _, _ = stitch.stitch(locs, infos)
        assert len(out[0]) < n_total
        tiles_per_site = out[0].groupby("site")["tile"].nunique()
        # only sites right at a seam, whose localizations scatter
        # across it, are split between tiles
        assert (tiles_per_site > 1).mean() < 0.01

    def test_frames_offset_in_acquisition_order(self):
        rng = np.random.default_rng(4)
        locs, infos, _, _ = _grid(rng, n_cols=2, n_rows=1)
        for t, locs_ in enumerate(locs):
            locs_["tile"] = t
        # the second file was acquired first
        mm = [info[0]["Micro-Manager Metadata"] for info in infos]
        mm[0]["ReceivedTime"], mm[1]["ReceivedTime"] = (
            mm[1]["ReceivedTime"],
            mm[0]["ReceivedTime"],
        )
        out, out_infos, _ = stitch.stitch(locs, infos, cut_seams=False)
        frames = out[0].groupby("tile")["frame"]
        assert frames.min()[1] < FRAMES and frames.max()[1] < FRAMES
        assert frames.min()[0] >= FRAMES
        assert out_infos[0][0]["Frames"] == 2 * FRAMES
        assert out_infos[0][-1]["Frame offsets"] == [0, FRAMES]
        assert out[0]["frame"].is_monotonic_increasing

        out, out_infos, _ = stitch.stitch(
            locs, infos, cut_seams=False, offset_frames=False
        )
        assert out[0]["frame"].max() < FRAMES
        assert out_infos[0][0]["Frames"] == FRAMES

    def test_several_targets_per_tile(self):
        """Two targets imaged at every position: files at the same stage
        position form one tile, and each target is merged on its
        own."""
        rng = np.random.default_rng(5)
        locs_a, infos_a, origins, _ = _grid(rng, n_cols=2, n_rows=2)
        # a second, sparse target at the same positions, with its own
        # sites
        sites_b = _sample(rng, 2000, 2000, density=0.002)
        locs, infos, paths = [], [], []
        for t, (locs_, info) in enumerate(zip(locs_a, infos_a)):
            size = (info[0]["Width"], info[0]["Height"])
            locs_b = _tile_locs(rng, sites_b, origins[t], size, 0.0)
            locs += [locs_, locs_b]
            mm = info[0]["Micro-Manager Metadata"]
            stage_um = (mm["XPositionUm"], mm["YPositionUm"])
            infos += [info, _info(size, stage_um)]
            paths += [f"tile{t}_a.hdf5", f"tile{t}_b.hdf5"]
        out, out_infos, report = stitch.stitch(
            locs,
            infos,
            use_for_alignment=[True, False] * 4,
            paths=paths,
        )
        np.testing.assert_array_equal(report["tiles"], np.repeat(range(4), 2))
        assert report["targets"] == [0, 1]
        assert len(out) == 2
        np.testing.assert_allclose(
            _relative(report["positions"]), _relative(origins), atol=0.05
        )
        assert out_infos[1][-1]["Stitched files"] == paths[1::2]
        # the sparse target is placed like the dense one: its sites
        # land where they are in the sample
        site_x = out[1].groupby("site")["x"].mean()
        shift = report["positions"][0] - origins[0]
        np.testing.assert_allclose(
            site_x.to_numpy(),
            sites_b[site_x.index.to_numpy(), 0] + shift[0],
            atol=0.2,
        )

    def test_tile_without_overlap_keeps_initial_position(self):
        rng = np.random.default_rng(6)
        locs, infos, origins, _ = _grid(rng, n_cols=2, n_rows=1)
        far = locs[1].copy()
        locs.append(far)
        infos.append(_info((500, 400)))
        for info in infos:
            info[0].pop("Micro-Manager Metadata", None)
        positions = np.vstack([origins, origins[1] + (2000.0, 0.0)])
        with pytest.warns(UserWarning, match="initial position"):
            _, _, report = stitch.stitch(locs, infos, positions=positions)
        assert report["unconnected"] == [2]
        relative = _relative(report["positions"])
        np.testing.assert_allclose(
            relative[2], (positions - positions[0])[2], atol=1e-6
        )

    def test_mismatched_pixel_sizes_raise(self):
        rng = np.random.default_rng(7)
        locs, infos, _, _ = _grid(rng, n_cols=2, n_rows=1)
        infos[1][1]["Pixelsize"] = 100.0
        with pytest.raises(ValueError, match="different pixel sizes"):
            stitch.stitch(locs, infos)

    def test_missing_stage_positions_raise(self):
        rng = np.random.default_rng(8)
        locs, infos, _, _ = _grid(rng, n_cols=2, n_rows=1)
        del infos[0][0]["Micro-Manager Metadata"]
        assert stitch.stage_positions(infos) is None
        with pytest.raises(ValueError, match="stage positions"):
            stitch.stitch(locs, infos)


class TestHelpers:
    def test_group_tiles(self):
        positions = np.array(
            [[0.0, 0.0], [0.4, -0.2], [100.0, 0.0], [100.3, 0.0], [0, 100]]
        )
        np.testing.assert_array_equal(
            stitch.group_tiles(positions, 5), [0, 0, 1, 1, 2]
        )
        np.testing.assert_array_equal(stitch.group_tiles(None, 3), [0, 1, 2])

    def test_stage_to_camera(self):
        positions = np.array([[10.0, 20.0], [10.13, 20.0], [10.0, 20.26]])
        camera = stitch.stage_to_camera(positions, 130.0, "-y, x")
        np.testing.assert_allclose(camera, [[0, 0], [0, 1], [-2, 0]])

    def test_solve_positions_drops_inconsistent_pair(self):
        truth = np.array([[0.0, 0.0], [100.0, 0.0], [0.0, 100.0]])

        def pair(a, b, error=(0.0, 0.0), matches=1000, fraction=0.6):
            offset = truth[b] - truth[a] + error
            return {
                "tiles": (a, b),
                "offset": tuple(offset),
                "dz": 10.0 * (b - a),
                "score": 0.5,
                "matches": matches,
                "fraction": fraction,
            }

        # the wrong offset has the most matches, hence the smallest
        # share of the loop's error, but the lowest fraction matched
        pairs = [pair(0, 1), pair(0, 2), pair(1, 2, (3.0, -2.0), 2000, 0.3)]
        positions, z_offsets, pairs, unconnected = stitch.solve_positions(
            pairs, truth + 5.0
        )
        np.testing.assert_allclose(positions, truth + 5.0, atol=1e-9)
        assert [p["used"] for p in pairs] == [True, True, False]
        assert pairs[2]["status"] == "inconsistent"
        assert unconnected == []
        np.testing.assert_allclose(z_offsets, [0.0, 10.0, 20.0])

    def test_solve_positions_skips_weak_pairs(self):
        pairs = [
            {
                "tiles": (0, 1),
                "offset": (50.0, 0.0),
                "dz": None,
                "score": 0.5,
                "matches": 1000,
                "fraction": 0.05,
            },
            {
                "tiles": (1, 2),
                "offset": (90.0, 0.0),
                "dz": None,
                "score": None,
                "matches": 0,
                "fraction": 0.0,
            },
        ]
        initial = np.array([[0.0, 0.0], [100.0, 0.0], [200.0, 0.0]])
        positions, _, pairs, unconnected = stitch.solve_positions(
            pairs, initial
        )
        np.testing.assert_array_equal(positions, initial)
        assert [p["status"] for p in pairs] == ["weak", "empty"]
        assert unconnected == [1, 2]

    def test_seam_mask_cuts_in_the_middle(self):
        positions = np.array([[0.0, 0.0], [90.0, 0.0]])
        sizes = np.array([[100.0, 100.0], [100.0, 100.0]])
        x = np.array([10.0, 94.0, 96.0, 99.0])
        y = np.full(4, 50.0)
        np.testing.assert_array_equal(
            stitch.seam_mask(x, y, 0, positions, sizes),
            [True, True, False, False],
        )
        np.testing.assert_array_equal(
            stitch.seam_mask(x, y, 1, positions, sizes),
            [False, False, True, True],
        )


def test_cli_saves_one_file_per_target(tmp_path):
    rng = np.random.default_rng(9)
    locs, infos, origins, _ = _grid(rng, n_cols=2, n_rows=1)
    for t, (locs_, info) in enumerate(zip(locs, infos)):
        io.save_locs(str(tmp_path / f"tile{t}.hdf5"), locs_, info)
    cli._stitch([str(tmp_path / "tile*.hdf5")])
    stitched, info = io.load_locs(str(tmp_path / "tile0_stitched.hdf5"))
    assert info[-1]["Generated by"].endswith("Stitch")
    offsets = np.array(info[-1]["Tile offsets x (cam. px)"])
    np.testing.assert_allclose(
        offsets[1] - offsets[0], origins[1, 0] - origins[0, 0], atol=0.05
    )
    assert stitched["x"].max() < info[0]["Width"]
